assert(data.includes("createStateRevenueSyntheticBusinesses(EKIRS_JURISDICTION)"), "EKIRS data must be generated by the reusable deterministic synthetic-data service.");
assert(synthetic.includes("createStateRevenueSyntheticBusinesses"), "Reusable state revenue synthetic-data generator is missing.");
assert(exists("src/components/state-revenue/state-revenue-components.tsx"), "Reusable state revenue components must exist.");
assert(exists("docs/state-revenue-security-architecture.md"), "State revenue security architecture document must exist.");

const neutralSources = [
  ["src/lib/state-revenue/synthetic-data.ts", synthetic],
  ["src/lib/state-revenue/onboarding.ts", onboarding],
  ["src/components/state-revenue/state-revenue-components.tsx", components],
];
const forbiddenNeutralTokens = ["EKIRS", "BIN-EK", "ekirs.dbin.ng", "/dashboard/ekirs", "ekiti-state-internal-revenue-service"];
for (const [file, source] of neutralSources) {
  for (const token of forbiddenNeutralTokens) {
    assert(!source.includes(token), `${file} must not depend on ${token}.`);
  }
}
assert(!components.includes("Ekiti geography foundation"), "Shared geography component must be jurisdiction-neutral.");

function loadTsModule(file, requireMap = {}) {
  const source = read(file);
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
      esModuleInterop: true,
      importsNotUsedAsValues: ts.ImportsNotUsedAsValues.Remove,
    },
    fileName: file,
  });
  const cjsModule = { exports: {} };
  vm.runInNewContext(outputText, {
    module: cjsModule,
    exports: cjsModule.exports,
    require(specifier) {
      if (specifier in requireMap) return requireMap[specifier];
      throw new Error(`Unexpected import ${specifier} from ${file}`);
    },
  });
  return cjsModule.exports;
}

